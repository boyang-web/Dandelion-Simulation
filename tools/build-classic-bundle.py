#!/usr/bin/env python3
"""Build a classic-script bundle so index.html also works from file://.

The modular sources remain the source of truth for the local server.
This script wraps three.module.js into a window.THREE global and turns the
app modules into a tiny CommonJS-like registry (one IIFE per module), which
avoids top-level name collisions between modules.
"""

from pathlib import Path
import base64
import json
import posixpath
import re

ROOT = Path(__file__).resolve().parent.parent
THREE = ROOT / 'vendor' / 'three.module.js'
THREE_GLOBAL = ROOT / 'vendor' / 'three.global.js'
ENTRIES = {
    'src/main.js': 'game',
    'prototype/js/main.js': 'prototype',
    'src/engine/vegetation-preview.js': 'vegetation',
    'src/engine/landmarks-preview.js': 'landmarks',
    'src/engine/distant.js': 'distant',
    'src/engine/valley-preview.js': 'valley',
}

IMPORT_RE = re.compile(
    r"""^import\s+(\{[^}]*\}|\* as [\w$]+|[\w$]+)\s+from\s+['"]([^'"]+)['"];?[ \t]*$""",
    re.MULTILINE
)
EXPORT_DECL_RE = re.compile(
    r"^export\s+(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)",
    re.MULTILINE
)
EXPORT_LIST_RE = re.compile(r"^export\s*\{([^}]*)\};?\s*$", re.MULTILINE)


def make_three_global():
    source = THREE.read_text(encoding='utf-8')
    match = re.search(r"\nexport\s*\{([^}]*)\};?\s*$", source, re.MULTILINE)
    if not match:
        raise SystemExit('three.module.js: could not find final export block')
    names = []
    for part in match.group(1).split(','):
        part = part.strip()
        if not part:
            continue
        if ' as ' in part:
            orig, alias = [s.strip() for s in part.split(' as ', 1)]
            names.append(f'{alias}: {orig}')
        else:
            names.append(part)
    body = source[:match.start()]
    out = (
        '/* three.js r161 as a classic global — generated by tools/build-classic-bundle.py */\n'
        "(function () {\n'use strict';\n"
        + body
        + "\nwindow.THREE = { "
        + ', '.join(names)
        + " };\n})();\n"
    )
    THREE_GLOBAL.write_text(out, encoding='utf-8')
    print(f'wrote {THREE_GLOBAL.relative_to(ROOT)} ({len(out) / 1024:.0f} KB)')


def transform_module(key):
    path = ROOT / key
    code = path.read_text(encoding='utf-8')
    deps = []
    header = []

    for match in list(IMPORT_RE.finditer(code)):
        what = match.group(1).strip()
        spec = match.group(2).strip().split('?')[0]
        if spec in ('three', 'vue'):
            dep = spec
        elif spec.startswith('.'):
            dep = posixpath.normpath(
                posixpath.join(posixpath.dirname(key), spec)
            )
        else:
            raise SystemExit(f'{key}: unsupported import spec {spec}')

        if dep not in deps:
            deps.append(dep)

        if what.startswith('* as '):
            ns = what[5:].strip()
            if dep == 'three':
                header.append(f'const {ns} = d["three"].THREE;')
            else:
                raise SystemExit(f'{key}: namespace import from {dep} unsupported')
        elif what.startswith('{'):
            inner = what.strip('{}').strip()
            plain = []
            for part in inner.split(','):
                part = part.strip()
                if not part:
                    continue
                if ' as ' in part:
                    orig, alias = [s.strip() for s in part.split(' as ', 1)]
                    header.append(f'const {alias} = d["{dep}"].{orig};')
                else:
                    plain.append(part)
            if plain:
                header.append(f'const {{ {", ".join(plain)} }} = d["{dep}"];')
        else:
            header.append(f'const {what} = d["{dep}"].default;')

    code = IMPORT_RE.sub('', code)

    # Textures loaded from file URLs cannot be uploaded to WebGL on some browsers.
    def embed_texture(match):
        asset = path.parent / match.group(1)
        data = base64.b64encode(asset.read_bytes()).decode('ascii')
        return f'new URL("data:image/webp;base64,{data}")'

    code = re.sub(r"""new URL\(['"]([^'"]+\.webp)['"],\s*import\.meta\.url\)""", embed_texture, code)
    has_default = 'export default ' in code
    code = code.replace('export default ', 'const defaultExport = ')

    exported = []

    def export_decl(match):
        kind, name = match.group(1), match.group(2)
        exported.append(name)
        return f'{kind} {name}'

    code = EXPORT_DECL_RE.sub(export_decl, code)

    for match in list(EXPORT_LIST_RE.finditer(code)):
        for part in match.group(1).split(','):
            part = part.strip()
            if not part:
                continue
            if ' as ' in part:
                orig, alias = [s.strip() for s in part.split(' as ', 1)]
                exported.append(alias)
                header.append(f'const {alias} = {orig};')
            else:
                exported.append(part)
    code = EXPORT_LIST_RE.sub('', code)

    if re.search(r'^\s*export\s', code, re.MULTILINE):
        raise SystemExit(f'{key}: unhandled export remains')

    exported = list(dict.fromkeys(exported))
    if has_default:
        exported.append('default: defaultExport')
    ret = 'return { ' + ', '.join(exported) + ' };' if exported else 'return {};'

    return {
        'key': key,
        'deps': deps,
        'factory': (
            f'defs[{json.dumps(key)}] = {{ deps: {json.dumps(deps)}, '
            f'factory: function (d) {{\n'
            + '\n'.join('      ' + line for line in header)
            + '\n' + code + '\n' + ret + '\n} };\n'
        )
    }


def main():
    make_three_global()
    parts = [
        '/* Generated by tools/build-classic-bundle.py — do not edit by hand. */',
        "(function () {",
        "  'use strict';",
        '  var bundleUrl = document.currentScript.src;',
        '  var defs = {};',
        '  var cache = {};',
        '  function req(id) {',
        '    if (cache[id]) return cache[id];',
        '    var def = defs[id];',
        '    if (!def) throw new Error("bundle: missing module " + id);',
        '    var d = {};',
        '    for (var i = 0; i < def.deps.length; i++) {',
        '      var dep = def.deps[i];',
        '      d[dep] = req(dep);',
        '    }',
        '    var exp = def.factory(d) || {};',
        '    cache[id] = exp;',
        '    return exp;',
        '  }',
        '  defs["three"] = { deps: [], factory: function () { return { THREE: window.THREE }; } };',
    ]

    parts.append('defs["vue"] = { deps: [], factory: function () { return window.Vue; } };')
    for entry, name in ENTRIES.items():
        modules = {}

        def collect(key):
            if key in modules or key in ('vue', 'three'):
                return
            module = transform_module(key)
            modules[key] = module['factory']
            for dep in module['deps']:
                collect(dep)

        collect(entry)
        out_path = ROOT / 'src' / 'engine' / f'bundle-{name}.js'
        body = parts + list(modules.values()) + [f'  req("{entry}");', '})();']
        out = '\n'.join(body)
        out_path.write_text(out, encoding='utf-8')
        print(f'wrote {out_path.relative_to(ROOT)} ({len(out) / 1024:.0f} KB)')


if __name__ == '__main__':
    main()