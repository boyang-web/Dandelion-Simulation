#!/usr/bin/env python3
"""Bake the production scene into one self-contained HTML file.

The result has no external requests: CSS, three.js (classic global build) and
the application bundle are inlined. That makes it possible to publish one file
(or hand it over / open it from a USB stick) while keeping the source tree
modular.

    python3 tools/build-single-file.py

Output: dist/dandelion.html
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'dist' / 'dandelion.html'

HTML = ROOT / 'index.html'
CSS = ROOT / 'css' / 'style.css'
THREE = ROOT / 'vendor' / 'three.global.js'
BUNDLE = ROOT / 'js' / 'bundle.js'


def inline_safe(text: str, tag: str, path: Path) -> str:
    closing = f'</{tag}'
    if closing.lower() in text.lower():
        raise SystemExit(f'{path}: cannot inline, contains {closing}>')
    return text


def main() -> None:
    html = HTML.read_text(encoding='utf-8')
    html = html.replace(
        '<!doctype html>',
        '<!doctype html>\n<!-- Generated by tools/build-single-file.py; do not edit. -->',
        1
    )
    css = inline_safe(CSS.read_text(encoding='utf-8'), 'style', CSS)
    three = inline_safe(THREE.read_text(encoding='utf-8'), 'script', THREE)
    bundle = inline_safe(BUNDLE.read_text(encoding='utf-8'), 'script', BUNDLE)

    marker = '<link rel="stylesheet" href="./css/style.css" />'
    if marker not in html:
        raise SystemExit('index.html: stylesheet link not found')
    html = html.replace(marker, f'<style>\n{css}\n  </style>')

    importmap = re.compile(
        r'\s*<script type="importmap">.*?</script>', re.DOTALL
    )
    html = importmap.sub('', html, count=1)

    loader = re.compile(
        r'  <script>\s*\(function \(\) \{\s*'
        r'// file:// blocks ES modules; use the generated classic bundle there\.'
        r'.*?</script>',
        re.DOTALL
    )
    scripts = (
        '  <script>\n'
        '    /* three.js r161, classic global build */\n'
        f'{three}\n'
        '  </script>\n'
        '  <script>\n'
        '    /* application bundle: production boot, no dev console */\n'
        f'{bundle}\n'
        '  </script>'
    )
    html, count = loader.subn(lambda _m: scripts, html, count=1)
    if count != 1:
        raise SystemExit('index.html: classic-bundle loader not found')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding='utf-8')

    size = OUT.stat().st_size
    print(f'wrote {OUT.relative_to(ROOT)} ({size / 1024 / 1024:.2f} MB)')


if __name__ == '__main__':
    main()